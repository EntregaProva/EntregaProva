import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";
const service = process.env.CLOUD_RUN_SERVICE;
const region = process.env.GCP_REGION;
if (!service || !region) throw new Error("Configure CLOUD_RUN_SERVICE e GCP_REGION");
const { hosting } = JSON.parse(readFileSync("firebase.json", "utf8"));
hosting.public = resolve(hosting.public);
hosting.rewrites = hosting.rewrites.map(rule => rule.run ? { ...rule, run: { serviceId: service, region, pinTag: true } } : rule);
mkdirSync(".firebase", { recursive: true });
writeFileSync(".firebase/cp3-hosting.json", JSON.stringify({ hosting }, null, 2));
